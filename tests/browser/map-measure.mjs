const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const locations = JSON.parse(readFileSync(new URL('../../public/locations.json', import.meta.url)));
const parents = new Set(locations.filter(location => location.type === 'kpw' && (location.coords || location.legacyCityCoords)).map(location => location.name));
const linkCount = locations.filter(location => location.type === 'kas' && (location.coords || location.legacyCityCoords) && parents.has(location.kpw)).length;
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox']});
try {
 for (const width of [1440, 390]) {
  const page = await browser.newPage({viewport: {width, height: 950}}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('https://**', route => route.abort());
  await page.route('**/api/inarisk?*', route => route.fulfill({json: {services: []}}));
  await page.goto((process.env.BASE_URL || 'http://localhost:3002') + '/#peta');
  await page.waitForSelector('#map-measure');
  assert.equal(linkCount, 87);
  assert.equal(await page.locator('.kpw-kas-link').count(), linkCount);
  assert.equal(await page.locator('#visible-count').textContent(), '133');
  assert.match(await page.locator('#headquarters-count').textContent(), /Kantor Pusat/);
  const mapped = await page.locator('.marker-container').evaluateAll(markers =>
    markers.reduce((total, marker) => total + Number(marker.querySelector('.cluster-count')?.textContent ?? 1), 0));
  assert.equal(mapped, 134);
  assert.equal(await page.locator('.kpw-kas-link[stroke-dasharray]').count(), 0);
  assert.equal(await page.locator('.kpw-kas-link[stroke-width="2"]').count(), 67);
  await page.locator('.map-filters [data-type="kpw"]').click();
  assert.equal(await page.locator('.kpw-kas-link').count(), 0);
  await page.locator('.map-filters [data-type="all"]').click();
  assert.equal(await page.locator('.kpw-kas-link').count(), linkCount);
  const korwil = page.getByRole('group', {name: 'Korwil jaringan pada peta'});
  assert.equal(await korwil.getByRole('button').count(), 6);
  const scale = await page.locator('.leaflet-control-scale').boundingBox();
  const buttons = await korwil.boundingBox();
  assert.ok(buttons.y + buttons.height <= scale.y);
  const toggle = page.getByRole('button', {name: 'Korwil', expanded: true});
  const first = await korwil.getByRole('button').first().boundingBox();
  const second = await korwil.getByRole('button').nth(1).boundingBox();
  assert.ok(second.y > first.y && second.x === first.x);
  await toggle.click();
  assert.equal(await korwil.isVisible(), false);
  await page.getByRole('button', {name: 'Korwil', expanded: false}).click();
  assert.equal(await korwil.isVisible(), true);
  const sumatera = korwil.getByRole('button', {name: 'Sumatera'});
  await sumatera.click();
  assert.equal(await sumatera.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#region').inputValue(), 'Sumatera');
  const sumateraCount = locations.filter(location => location.type === 'kas' && location.region === 'Sumatera').length + 13;
  assert.equal(await page.locator('#visible-count').textContent(), String(sumateraCount));
  const regionalMarkers = await page.locator('.marker-container').evaluateAll(markers =>
    markers.reduce((total, marker) => total + Number(marker.querySelector('.cluster-count')?.textContent ?? 1), 0));
  assert.equal(regionalMarkers, sumateraCount);
  await korwil.getByRole('button', {name: 'Semua'}).click();
  assert.equal(await page.locator('#visible-count').textContent(), '133');
  assert.equal(await page.locator('#data-nav, #distance-nav, #mobile-distance-nav').count(), 0);
  assert.equal(await page.locator('.nav-placeholder').count(), 0);
  await page.locator('#map-measure').click();
  assert.equal(await page.locator('#distance-panel select').count(), 0);
  const map = await page.locator('#map').boundingBox();
  const click = async (x, y) => page.mouse.click(map.x + map.width * x, map.y + map.height * y);
  await click(.45, .2); await click(.55, .25); await click(.65, .2);
  await page.waitForFunction(() => document.querySelector('#distance-result')?.dataset.pointCount === '3');
  const meters = Number(await page.locator('#distance-result').getAttribute('data-meters'));
  assert.ok(meters > 0);
  await page.locator('#distance-undo').click();
  assert.equal(await page.locator('#distance-result').getAttribute('data-point-count'), '2');
  assert.ok(Number(await page.locator('#distance-result').getAttribute('data-meters')) < meters);
  await page.locator('#distance-finish').click();
  await click(.4, .2);
  assert.equal(await page.locator('#distance-result').getAttribute('data-point-count'), '2');
  await page.screenshot({path: `/tmp/map-measure-${width}.png`});
  await page.locator('#distance-clear').click();
  assert.equal(await page.locator('#distance-result').getAttribute('data-point-count'), '0');
  await page.keyboard.press('Escape');
  assert.ok(await page.locator('#distance-panel').isHidden());
  assert.equal(await page.locator('#map-measure').getAttribute('aria-pressed'), 'false');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  await page.close();
  console.log('PASS: map drawing, multiple segments, undo, finish, restart, Escape and navigation; viewport', width);
 }
} finally { await browser.close(); }
